  await page.evaluate(() => { window.failNextSend = true })
  await page.getByRole('button', { name: 'Receber código por e-mail' }).click()
  await page.getByRole('alert').filter({ hasText: 'Não foi possível confirmar o envio' }).waitFor()
  assert.equal(await page.getByLabel('E-mail', { exact: true }).inputValue(), 'member@example.invalid')
  await page.clock.fastForward(61000)
  await page.getByRole('button', { name: 'Receber código por e-mail' }).click()
