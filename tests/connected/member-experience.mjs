  await page.getByLabel('Código enviado por e-mail').fill('111111')
  await page.getByRole('button', { name: 'Confirmar e-mail' }).click()
  await page.getByRole('alert').filter({ hasText: 'Código inválido' }).waitFor()
  await page.clock.fastForward(61000)
  await page.getByRole('button', { name: 'Reenviar código' }).click()
  await page.getByRole('button', { name: 'Corrigir e-mail' }).click()
  await page.getByRole('button', { name: 'Voltar aos dados pessoais' }).click()
  assert.equal(await page.getByLabel('Nome completo').inputValue(), 'Associado sintético')
  assert.equal(await page.getByLabel('CPF', { exact: true }).inputValue(), '52998224725')
