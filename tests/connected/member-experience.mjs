  await page.getByRole('button', { name: 'Continuar para o e-mail' }).click()
  await page.getByLabel('E-mail', { exact: true }).fill('corrected@example.invalid')
  await page.clock.fastForward(61000)
  await page.getByRole('button', { name: 'Receber código por e-mail' }).click()
