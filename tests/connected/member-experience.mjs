  await page.getByRole('heading', { name: 'Sua foto para o cartão' }).waitFor()
  const calls = await page.evaluate(() => window.experienceEvents)
  assert.deepEqual(calls.filter(x => x.action === 'verify' && x.token === '123456').slice(-2).map(x => [x.purpose, x.channel]), [['signup', 'email'], ['attach', 'sms']])
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: '/tmp/rkmed-member-signup-mobile.png', fullPage: true })
  const saved = calls.filter(x => x.enrollment).at(-1).enrollment
  assert.equal(saved.name, 'Associado sintético')
  assert.equal(saved.cpf, '52998224725')
  assert.equal(calls.filter(x => x.action === 'verify' && x.channel === 'sms').length, 1, 'Retomada não consome o SMS novamente')
  await page.getByRole('button', { name: 'Tirar foto', exact: true }).click({ timeout: 90000 })
