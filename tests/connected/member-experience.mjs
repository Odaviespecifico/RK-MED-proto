  await page.getByRole('alert').filter({ hasText: 'expirou' }).waitFor()
  await page.getByRole('button', { name: 'Reenviar código' }).click()
  await page.getByLabel('Código enviado por e-mail').fill('123456')
  await page.getByRole('button', { name: 'Confirmar e-mail' }).click()
  await page.getByRole('button', { name: 'Receber código pelo SMS' }).waitFor()
  assert.equal(await page.getByLabel('Celular com DDD').inputValue(), '')
  await page.getByLabel('Celular com DDD').fill('81999990001')
  await page.getByRole('button', { name: 'Receber código pelo SMS' }).click()
  await page.getByRole('button', { name: 'Corrigir celular' }).click()
  await page.getByLabel('Celular com DDD').fill('81999990002')
